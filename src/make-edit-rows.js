#!/usr/bin/env node
/**
 * npm run make-edit-rows  ->  writes apps-script/AddEditRows.gs from src/edit-catalog.
 * Paste that file into the sheet's Apps Script and run addEditRows() once (safe to run again:
 * rows whose Page + Scenario already exist in the tab are skipped).
 */
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './config.js';
import { editCatalog } from './edit-catalog/index.js';

const rows = editCatalog();
// Most texts repeat across the 26 V2 pages: store each distinct string once and refer to it by index.
const STR = [], at = new Map();
const ix = s => { if (!at.has(s)) at.set(s, STR.push(s) - 1); return at.get(s); };
const bySheet = {};
for (const r of rows) (bySheet[r.sheet] ||= []).push([r.module, r.page, r.list, r.scenario, r.foa, r.taxable, r.payslip, r.name, r.ref, r.applicable, r.other, r.steps, r.expected].map(ix));

const gs = `/**
 * Ticket 2161 - Edit test cases. GENERATED by \`npm run make-edit-rows\` from src/edit-catalog: edit that, not this.
 *
 * Paste into the sheet's Apps Script (Extensions > Apps Script) as a new file and run addEditRows() once.
 * Appends ${rows.length} "Edit: ..." rows to the DP tabs below, continuing each tab's TC IDs (DPPD-0559...).
 * Safe to run again: a row whose Page + Scenario already exists in its tab is skipped. Links are built from the
 * host of the tab's existing links (no address is stored in this file).
 */
const EDIT_COLS = ['Module', 'Page', '(list)', 'Scenario', 'Frequency (FOA)', 'Taxable', 'Include in Payslip', 'Name', 'Reference File', 'Applicable To', 'Other Inputs', 'Steps to Test', 'Expected Result'];
// Every text once; EDIT_ROWS cells are indexes into it (in EDIT_COLS order).
const EDIT_STR = ${JSON.stringify(STR, null, 0).replace(/","/g, '",\n  "')};
const EDIT_ROWS = ${JSON.stringify(bySheet, null, 0).replace(/\],\[/g, '],\n  [').replace(/":\[\[/g, '":[\n  [')};

function addEditRows() {
  const ss = SpreadsheetApp.getActive();
  for (const k of Object.keys(EDIT_ROWS)) EDIT_ROWS[k] = EDIT_ROWS[k].map(r => r.map(i => (typeof i === 'number' ? EDIT_STR[i] : i)));
  const report = [];
  for (const name of Object.keys(EDIT_ROWS)) {
    const sh = ss.getSheetByName(name);
    if (!sh) { report.push(name + ': tab not found, skipped'); continue; }
    const width = sh.getLastColumn();
    const head = sh.getRange(4, 1, 1, width).getValues()[0].map(String);
    const col = h => head.indexOf(h);
    const cId = col('TC ID'), cPage = col('Page'), cScen = col('Scenario'), cV = col('Vercel Link'), cN = col('.NET Link');
    if (cId < 0 || cPage < 0 || cScen < 0) { report.push(name + ': headers not recognised, skipped'); continue; }
    const n = Math.max(0, sh.getLastRow() - 4);
    const data = n ? sh.getRange(5, 1, n, width).getValues() : [];
    // Last row that has a TC ID (helper formulas may reach further down), the ID prefix and the highest number.
    let last = 4, prefix = null, max = 0, vHost = '', nHost = '';
    const have = {};
    data.forEach((r, i) => {
      const id = String(r[cId] || '');
      if (!id) return;
      last = 5 + i;
      const m = id.match(/^(.*?)-(\\d+)$/);
      if (m) { prefix = prefix || m[1]; max = Math.max(max, Number(m[2])); }
      have[r[cPage] + '|' + r[cScen]] = true;
      if (!vHost && cV >= 0) vHost = (String(r[cV]).match(/^https?:\\/\\/[^/]+/) || [''])[0];
      if (!nHost && cN >= 0) nHost = (String(r[cN]).match(/^https?:\\/\\/[^/]+/) || [''])[0];
    });
    if (!prefix) { report.push(name + ': no existing TC IDs to continue from, skipped'); continue; }
    const todo = EDIT_ROWS[name].filter(r => !have[r[1] + '|' + r[3]]);
    if (!todo.length) { report.push(name + ': nothing new'); continue; }
    const start = last + 1;
    if (start + todo.length - 1 > sh.getMaxRows()) sh.insertRowsAfter(sh.getMaxRows(), start + todo.length - 1 - sh.getMaxRows());
    const values = {};
    const put = (h, i, v) => { const c = col(h); if (c < 0) return; (values[c] = values[c] || [])[i] = [v]; };
    todo.forEach((r, i) => {
      put('TC ID', i, prefix + '-' + String(max + 1 + i).padStart(4, '0'));
      EDIT_COLS.forEach((h, k) => { if (h !== '(list)') put(h, i, r[k]); });
      put('Vercel Link', i, vHost + r[2]);
      put('.NET Link', i, nHost + r[2]);
    });
    // One write per known column: "(auto)" / helper columns next to them are left alone...
    for (const c of Object.keys(values)) sh.getRange(start, Number(c) + 1, todo.length, 1).setValues(values[c]);
    // ...except that a formula in the last existing row of an "(auto)" column is carried down to the new rows.
    head.forEach((h, c) => {
      if (!/\\(auto\\)/.test(h) || last < 5) return;
      const f = sh.getRange(last, c + 1).getFormulaR1C1();
      if (f) sh.getRange(start, c + 1, todo.length, 1).setFormulaR1C1(f);
    });
    if (last >= 5) sh.getRange(last, 1, 1, width).copyTo(sh.getRange(start, 1, todo.length, width), SpreadsheetApp.CopyPasteType.PASTE_FORMAT, false);
    report.push(name + ': added ' + todo.length + ' (' + prefix + '-' + String(max + 1).padStart(4, '0') + ' .. ' + prefix + '-' + String(max + todo.length).padStart(4, '0') + ')');
  }
  Logger.log(report.join('\\n'));
  return report;
}
`;
const out = path.join(ROOT, 'apps-script', 'AddEditRows.gs');
fs.writeFileSync(out, gs.replace(/\n/g, '\r\n'));
console.log(`Wrote ${out}: ${rows.length} rows (${Object.entries(bySheet).map(([k, v]) => `${k.slice(5)} ${v.length}`).join(', ')})`);
